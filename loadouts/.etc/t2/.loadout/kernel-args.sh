#!/bin/sh
# The kernel arguments Omarchy's installer writes for T2 Macs (the t2-kait2en
# branch's install/hardware/apple/fix-t2.sh), word for word, kept against
# upstream Omarchy migrations that rewrite the file: #6562 (August 2026) once
# swapped pcie_ports=compat for pm_async=off, copying KaiT2en's arguments of
# the time for linux-t2. KaiT2en has since moved back, and on this Mac
# (linux-omarchy, KaiT2en drivers, t2smp) these took the wake from deep sleep
# from ~16 s to ~1 s:
#
#   pci=noaer          Apple's firmware denies AER, and Linux using it anyway
#                      stalls resume for seconds.
#   pcie_ports=compat  no native PCIe port services on the Thunderbolt
#                      bridges, which otherwise wait ~10 s each on resume
#                      (costs native PCIe hotplug of Thunderbolt docks/eGPUs).
#   no pm_async=off    KaiT2en's drivers resume in parallel.
#
# Not applicable while linux-t2 is installed: its t2bce wants pm_async=off,
# and the file is shared by every kernel's entry.
#
# limine-mkinitcpio rebuilds the UKIs (command lines included) and the boot
# entries; takes effect at the next boot. check asks the booted command line
# too, since /boot isn't readable unprivileged.
# Modes: `check` / `install` (default).
set -eu

CONF=/etc/limine-entry-tool.d/t2-mac.conf
WANT='# Generated by Omarchy installer for T2 Mac support
KERNEL_CMDLINE[default]+=" intel_iommu=on iommu=pt mem_sleep_default=deep pci=noaer pcie_ports=compat"'

applicable() {
  lspci -nn 2>/dev/null | grep -q '106b:180[12]' || return 1
  ! pacman -Q linux-t2 >/dev/null 2>&1
}

booted_ok() {
  grep -qw pci=noaer /proc/cmdline &&
    grep -qw pcie_ports=compat /proc/cmdline &&
    ! grep -qw pm_async=off /proc/cmdline
}

case "${1:-install}" in
check)
  applicable || exit 0
  [ "$(cat "$CONF" 2>/dev/null)" = "$WANT" ]
  booted_ok
  ;;
install)
  if ! applicable; then
    echo "t2-kernel-args: not a T2 Mac, or linux-t2 is installed; nothing to do"
    exit 0
  fi
  rebuild=no
  if [ "$(cat "$CONF" 2>/dev/null)" != "$WANT" ]; then
    sudo mkdir -p "$(dirname "$CONF")"
    printf '%s\n' "$WANT" | sudo tee "$CONF" >/dev/null
    rebuild=yes
  fi
  # The image that booted didn't carry them: rebuild it too.
  booted_ok || rebuild=yes
  if [ "$rebuild" = yes ]; then
    sudo limine-mkinitcpio
    echo "t2-kernel-args: takes effect at the next boot"
  fi
  ;;
*) echo "usage: $0 [check|install]" >&2; exit 2 ;;
esac
